package com.foodordering.service;

import com.foodordering.dto.CustomerRequest;
import com.foodordering.entity.Customer;
import com.foodordering.exception.DuplicateEmailException;
import com.foodordering.repository.CustomerRepository;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

/**
 * Business logic for customers.
 */
@Service
public class CustomerService {

    private final CustomerRepository customerRepository;

    // Spring injects the repository for us (no "new" keyword needed).
    public CustomerService(CustomerRepository customerRepository) {
        this.customerRepository = customerRepository;
    }

    /**
     * Registers a new customer.
     *
     * The customer_id is NOT set here. It is generated by MySQL when
     * customerRepository.save() inserts the row, and Hibernate reads the
     * generated id back into the object we return.
     */
    @Transactional
    public Customer registerCustomer(CustomerRequest request) {
        String email = request.getEmail().trim();

        // Check 1: friendly check, so the user gets a clear error message.
        if (customerRepository.existsByEmailIgnoreCase(email)) {
            throw new DuplicateEmailException(
                    "A customer with email '" + email + "' already exists");
        }

        Customer customer = new Customer(
                request.getName().trim(),
                email,
                request.getPhone().trim());

        try {
            // save() runs an INSERT INTO customer (name, email, phone) VALUES (...)
            // and fills customer.customerId with the AUTO_INCREMENT value.
            return customerRepository.save(customer);
        } catch (DataIntegrityViolationException e) {
            // Check 2: safety net in case two people register the same email
            // at the exact same moment. The UNIQUE constraint on the email
            // column stops the second INSERT and MySQL raises this error.
            throw new DuplicateEmailException(
                    "A customer with email '" + email + "' already exists");
        }
    }

    /**
     * Returns every customer, newest id first.
     */
    public List<Customer> getAllCustomers() {
        return customerRepository.findAll();
    }
}
