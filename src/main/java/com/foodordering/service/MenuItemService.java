    private final MenuItemRepository menuItemRepository;

    // Spring injects the repository for us (no "new" keyword needed).
    public MenuItemService(MenuItemRepository menuItemRepository) {
        this.menuItemRepository = menuItemRepository;
    }

    /**
     * Returns every dish, grouped by category and sorted by name.
     */
    public List<MenuItem> getAllItems() {
        return menuItemRepository.findAllByOrderByCategoryAscNameAsc();
    }

    /**
     * Returns every dish of one category.
     */
    public List<MenuItem> getItemsByCategory(String category) {
        return menuItemRepository.findByCategoryIgnoreCaseOrderByNameAsc(category.trim());
    }

    /**
     * Returns the list of categories that are used on the menu.
     */
    public List<String> getCategories() {
        return menuItemRepository.findDistinctCategories();
    }

    /**
     * Returns one dish. Throws 404 when the id is not on the menu.
     */
    public MenuItem getItemById(Long itemId) {
        return menuItemRepository.findById(itemId)
                .orElseThrow(() -> new ResourceNotFoundException(
                        "No menu item found with id " + itemId));
    }

    /**
     * Adds a new dish to the menu.
     *
     * The item_id is NOT set here. It is generated by MySQL when
     * menuItemRepository.save() inserts the row, and Hibernate reads the
     * generated id back into the object we return.
     */
    @Transactional
    public MenuItem addItem(MenuItemRequest request) {
        String name = request.getName().trim();

        // Check 1: friendly check, so the user gets a clear error message.
        if (menuItemRepository.existsByNameIgnoreCase(name)) {
            throw new DuplicateMenuItemException(
                    "A menu item called '" + name + "' already exists");
        }

        MenuItem item = new MenuItem(
                name,
                request.getDescription() == null ? null : request.getDescription().trim(),
                request.getPrice(),
                request.getCategory().trim(),
                request.getImageUrl() == null ? null : request.getImageUrl().trim(),
                // When the client does not say anything, the dish is available.
                request.getAvailable() == null || request.getAvailable());

        try {
            // save() runs an INSERT INTO menu_item (name, description, price, ...)
            // and fills menuItem.itemId with the AUTO_INCREMENT value.
            return menuItemRepository.save(item);
        } catch (DataIntegrityViolationException e) {
            // Check 2: safety net in case two dishes with the same name are
            // added at the exact same moment. The UNIQUE constraint on the
            // name column stops the second INSERT and MySQL raises this error.
            throw new DuplicateMenuItemException(
                    "A menu item called '" + name + "' already exists");
        }
    }

    /**
     * Changes an existing dish (name, description, price, category, image).
     */
    @Transactional
    public MenuItem updateItem(Long itemId, MenuItemRequest request) {
        MenuItem item = getItemById(itemId);
        String name = request.getName().trim();

        // The new name must not belong to a different dish.
        if (!name.equalsIgnoreCase(item.getName())
                && menuItemRepository.existsByNameIgnoreCase(name)) {
            throw new DuplicateMenuItemException(
                    "A menu item called '" + name + "' already exists");
        }

        item.setName(name);
        item.setDescription(request.getDescription() == null ? null : request.getDescription().trim());
        item.setPrice(request.getPrice());
        item.setCategory(request.getCategory().trim());
        item.setImageUrl(request.getImageUrl() == null ? null : request.getImageUrl().trim());

        return menuItemRepository.save(item);
    }

    /**
     * Marks a dish as available / sold out.
     */
    @Transactional
    public MenuItem setAvailability(Long itemId, boolean available) {
        MenuItem item = getItemById(itemId);
        item.setAvailable(available);
        return menuItemRepository.save(item);
    }

    /**
     * Removes a dish from the menu.
     */
    @Transactional
    public void deleteItem(Long itemId) {
        MenuItem item = getItemById(itemId);
        menuItemRepository.delete(item);
    }

    /**
     * Adds the sample dishes to the menu - but only the ones that are not
     * there yet. This is why restarting the application never creates
     * duplicates: a dish is looked up by name before it is inserted.
     *
     * @return how many new rows were inserted
     */
    @Transactional
    public int seedSampleItems() {
        int inserted = 0;

        for (MenuItem sample : sampleItems()) {
            if (menuItemRepository.existsByNameIgnoreCase(sample.getName())) {
                continue;   // already on the menu -> do NOT create a duplicate
            }
            menuItemRepository.save(sample);
            inserted++;
        }

        return inserted;
    }

